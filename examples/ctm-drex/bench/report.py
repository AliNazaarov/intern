"""Write docs/results.md from the files in bench/results/, so no result number is typed by hand.

    python -m bench.report
"""

from __future__ import annotations

import json
from pathlib import Path

from bench.aggrefact import load_sample

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "bench" / "results"


def j(name: str) -> dict:
    return json.loads((R / name).read_text())


def aggrefact_rows() -> list[tuple]:
    base = j("aggrefact_summary.json")
    raw = j("aggrefact_raw.json")
    test = [r for r in load_sample() if r["split"] == "test"]
    neg = [r for r in test if r["label"] == 0]
    d = base["drex"]
    t = d["fitted_threshold"]
    missed = sum((raw["drex"][r["id"]].get("p_supported") or 0) >= t for r in neg)
    missed_05 = sum((raw["drex"][r["id"]].get("p_supported") or 0) >= 0.5 for r in neg)
    rows = [(f"Drex (drex-max-v1.1), threshold fitted on dev (at 0.5: {d['balanced_accuracy_thr_0.5']:.3f}, passes {missed_05})", d["balanced_accuracy_fitted"], missed, len(neg),
             d["seconds_p50"], d["cost_per_1000_claims_usd"])]
    files = {"haiku": base}
    for p in sorted(R.glob("aggrefact_summary_*.json")):
        files[p.stem.removeprefix("aggrefact_summary_")] = json.loads(p.read_text())
    for name, s in files.items():
        m = s.get(name)
        if not m or m.get("balanced_accuracy") is None:
            continue
        got = raw.get(name, {})
        if not all(r["id"] in got for r in neg):
            continue
        miss = sum(got[r["id"]].get("verdict") == "supported" for r in neg)
        rows.append((m.get("model") or name, m["balanced_accuracy"], miss, len(neg), m["seconds_p50"],
                     m["cost_per_1000_claims_usd"]))
    return rows


def petition_rows() -> list[tuple]:
    base = j("summary.json")
    d = base["drex_rules_fitted"]
    rows = [("Drex (drex-max-v1.1)", d["accuracy"], d["macro_f1"], d["missed_bad_claims"], d["false_alarms"],
             base["drex_speed"]["p50_s_per_petition"], base["drex_cost_per_1k_claims_usd"], 0)]
    files = {"haiku": base} | {p.stem.removeprefix("summary_"): json.loads(p.read_text()) for p in sorted(R.glob("summary_*.json"))
                               if p.stem != "summary_cases_pdf"}
    for name, s in files.items():
        if name not in s:
            continue
        m = s.get(f"{name}_rules") or s[name]
        rows.append((s.get(f"{name}_model") or name, m["accuracy"], m["macro_f1"], m["missed_bad_claims"],
                     m["false_alarms"], s[f"{name}_speed"]["p50_s_per_petition"], s[f"{name}_cost_per_1k_claims_usd"],
                     s.get(f"{name}_unparsed", 0)))
    return rows


def main() -> None:
    out = ["# Results", "", "Generated by `python -m bench.report` from `bench/results/`. Every number was measured in one run.", ""]
    rows = aggrefact_rows()
    out += ["## LLM-AggreFact sample: 150 held-out claims", "",
            "LLM-AggreFact is Tang, Laban and Durrett's benchmark (2024). Balanced accuracy differences under about 0.07 "
            "are within noise at n=150. Drex's threshold was fitted on 50 separate dev rows; the other models give one verdict.", "",
            "| Model | Balanced accuracy | Unsupported claims passed as supported | p50 seconds per claim | $ per 1,000 claims |",
            "|---|---|---|---|---|"]
    for name, ba, miss, n, sec, cost in sorted(rows, key=lambda r: r[5]):
        out.append(f"| {name} | {ba:.3f} | {miss} of {n} | {sec:.2f} | {cost:.3f} |")
    full = j("aggrefact_full_summary.json")
    out += ["", "## LLM-AggreFact full test set, Drex only", "",
            f"{full['claims_scored']:,} claims scored ({full['claims_failed']} failed), {full['requests']:,} requests (claims sharing a document asked together), "
            f"threshold 0.5. Average balanced accuracy across the 10 sub-datasets: **{full['average_balanced_accuracy']:.3f}**. "
            f"Input tokens {full['input_tokens']:,}, cost ${full['cost_usd']:.2f}, p50 {full['seconds_per_request_p50']:.2f} s per request. "
            "Source: a public re-upload of the test set (the official copy is gated), so leaderboard comparisons are approximate.", "",
            "| Sub-dataset | Balanced accuracy |", "|---|---|"]
    out += [f"| {k} | {v:.3f} |" for k, v in full["per_dataset_balanced_accuracy"].items()]
    prow = petition_rows()
    s = j("summary.json")
    out += ["", f"## Synthetic O-1A petitions: {s['test_claims']} held-out claims in {s['test_cases']} cases", "",
            "Our own synthetic set. Most models score near 1.00, so it ranks speed and cost, not accuracy. Drex's row "
            "includes the number rule (code) and its threshold; every other model gets the same number rule (its `_rules` "
            "score). Unparsed baseline verdicts count as errors, so they are neither missed nor correct.", "",
            "| Model | Accuracy | Macro-F1 | Missed bad claims | False alarms | p50 seconds per petition | $ per 1,000 claims | Unparsed |",
            "|---|---|---|---|---|---|---|---|"]
    for r in sorted(prow, key=lambda r: r[6]):
        out.append(f"| {r[0]} | {r[1]:.3f} | {r[2]:.3f} | {r[3]:.3f} | {r[4]:.3f} | {r[5]:.2f} | {r[6]:.3f} | {r[7]} |")
    pdf = j("summary_cases_pdf.json")
    ndi = j("ndi_parse.json")
    ndi_cost = sum(float(i["cost"]["total_usd"]) for i in ndi["items"] if i.get("cost"))
    out += ["", "## Exhibits as PDFs, parsed by NDI", "",
            f"{ndi['pdfs']} exhibit PDFs parsed by Nace Document Intelligence, {len(ndi['errors'])} errors, p50 "
            f"{ndi['seconds_p50']:.1f} s per page, ${ndi_cost:.2f} reported by NDI. Drex on the parsed text: accuracy "
            f"{pdf['drex_rules_fitted']['accuracy']:.3f} on the same {pdf['test_claims']} test claims, p50 "
            f"{pdf['drex_speed']['p50_s_per_petition']:.2f} s per petition."]
    t = j("telepathy.json")
    out += ["", f"## Read once, ask many ({t['case']}, {t['claims']} claims)", "",
            "| | Seconds | Input tokens |", "|---|---|---|",
            f"| All claims in one request against one read of the exhibits | {t['batched']['seconds']:.2f} | {t['batched']['input_tokens']:,} |",
            f"| One request per claim | {t['one_per_request']['seconds']:.2f} | {t['one_per_request']['input_tokens']:,} |"]
    (ROOT / "docs" / "results.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
